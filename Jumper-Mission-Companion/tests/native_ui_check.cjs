const {chromium}=require(process.env.MISSION_PLAYWRIGHT||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8767');
 await page.getByText('MuJoCo · official model',{exact:true}).waitFor();
 await page.waitForFunction(()=>Number(document.querySelector('#webgl-view').dataset.frames)>3);
 assert.equal(await page.locator('#webgl-view').isVisible(),true);
 const initial=await page.evaluate(async()=>await(await fetch('/api/state')).json());
 assert.equal(initial.performance.frame_number||0,0,'Browser view must not run Python graphics');
 assert.ok(initial.visual_pose.length>30);
 await page.getByLabel('Follow crab',{exact:true}).uncheck();
 assert.equal(await page.getByLabel('Follow crab',{exact:true}).isChecked(),false);
 await page.getByLabel('Follow crab',{exact:true}).check();
 const stage=await page.locator('#webgl-view').boundingBox();
 await page.mouse.move(stage.x+stage.width/2,stage.y+stage.height/2);
 await page.mouse.down();await page.mouse.move(stage.x+stage.width/2+70,stage.y+stage.height/2+25,{steps:8});await page.mouse.up();
 await page.getByRole('button',{name:'Reset camera',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.querySelector('#webgl-view').getContext('webgl2').getError()),0);
 await page.waitForFunction(()=>document.querySelector('#sim-speed').textContent.includes('real time'));
 await page.screenshot({path:'docs/dashboard-native.png',fullPage:true});
 await page.locator('#view-choice').selectOption('map');
 await page.locator('#physics-map').waitFor({state:'visible'});
 await page.locator('#view-choice').selectOption('image');
 await page.waitForFunction(()=>document.querySelector('#native-view').naturalWidth>0);
 assert.equal(await page.locator('#native-view').getAttribute('src'),'/api/stream');
 await page.locator('#view-choice').selectOption('browser');
 await page.locator('#webgl-view').waitFor({state:'visible'});
 await page.getByRole('button',{name:'03 Expressions'}).click();
 await page.getByRole('button',{name:'Joyful',exact:false}).click();
 try{await page.waitForFunction(()=>document.querySelector('#mode').textContent==='dance crab',null,{timeout:15000});}
 catch(e){fs.writeFileSync('docs/native-ui-failure.json',JSON.stringify(await page.evaluate(async()=>await (await fetch('/api/state')).json()),null,2));throw e;}
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.querySelector('#mode').textContent==='locomotion',null,{timeout:10000});
 await page.getByRole('button',{name:'01 Mission control'}).click();
 await page.getByRole('button',{name:'Start mission ↗'}).click();
 await page.waitForFunction(()=>document.querySelector('#nav-status').textContent==='running');
 const snapshot=await page.evaluate(async()=>await (await fetch('/api/state')).json());
 const cell=snapshot.navigation.path[3];
 const box=await page.locator('#maze').boundingBox();
 const size=Math.min(440/snapshot.maze.width,390/snapshot.maze.height);
 const ox=(440-size*snapshot.maze.width)/2,oy=(390-size*snapshot.maze.height)/2;
 await page.locator('#maze').click({position:{x:(ox+(cell[0]+.5)*size)*box.width/440,y:(oy+(cell[1]+.5)*size)*box.height/390}});
 await page.waitForFunction(()=>Number(document.querySelector('#replans').textContent)>=1);
 await page.waitForFunction(()=>document.querySelector('#nav-status').textContent==='complete',null,{timeout:90000});
 await page.screenshot({path:'docs/dashboard-native-complete.png',fullPage:true});
 // Loss of browser graphics must preserve physics and provide a usable view.
 await page.evaluate(()=>document.querySelector('#webgl-view').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
 await page.locator('#physics-map').waitFor({state:'visible'});
 assert.equal(await page.locator('#view-choice').inputValue(),'map');
 const fallback=await page.evaluate(async()=>await(await fetch('/api/state')).json());
 assert.equal(fallback.fault,null);assert.equal(fallback.robot.backend,'mujoco-official-jumper');
 assert.deepEqual(errors,[]);
 fs.writeFileSync('docs/native-ui-results.json',JSON.stringify({passed:true,tests:['official meshes animated from native poses in browser WebGL','Python rendering remains idle in default browser view','follow-camera toggle','drag orbit and camera reset with no WebGL errors','live 2D map view','MJPEG diagnostic fallback','switch back to browser 3D','live simulation speed readout','celebration routes to actual dance mode','Escape cancels native dance','native mission and live obstacle replan via dashboard','graphics context loss falls back to real physics in 2D'],pageErrors:errors},null,2));
 await browser.close();console.log('12 native UI checks passed.');
})().catch(e=>{console.error(e);process.exit(1)});
